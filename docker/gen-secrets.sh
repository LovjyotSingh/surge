#!/bin/sh
# Generates every credential and key the Compose platform needs (security audit Task C, §5 step 4):
#
#   .env                                  mode 600, read by docker compose (never commit it; it is gitignored)
#   docker/secrets/                       mode 700 (gitignored)
#     jwt.jwk                             auth-service's user-JWT signing key (docker/gen-jwt-key.sh)
#     gateway.jwk booking.jwk notification.jwk
#                                         internal identity signing keys, one per issuer (docker/gen-internal-keys.sh)
#     internal-jwks.json                  their public halves (mode 644)
#     redis-users.acl                     booking's Redis ACL: default user off, user "booking"
#     redis-edge-users.acl                the gateway's Redis ACL: default user off, user "gateway"
#                                         (each stores only the SHA-256 of the password)
#     rabbitmq-definitions.json           RabbitMQ users (salted SHA-256), vhost, permissions and ticket topology
#
# Every generated value is hex (URL-safe, no quotes or backslashes), so it is valid in a Eureka URL, a Kafka JAAS
# line, SQL and JSON alike: 48 characters (24 random bytes) for passwords, 64 for the ticket QR HMAC key.
#
# usage: docker/gen-secrets.sh [--force]
#   --force   replace an existing .env and the keys in docker/secrets/. Note what a new value does on an existing
#             stack: Redis, RabbitMQ, Kafka, the Elasticsearch "catalog" user, Eureka, config and the admin password
#             follow .env at the next `docker compose up`. MySQL users and the "elastic" password are set only when
#             their volumes are first created: change them by hand (ALTER USER / elasticsearch-reset-password) or
#             start from new volumes. New JWT keys sign everyone out; new internal keys need every service restarted.
#
# Needs: openssl, and a JDK for the key scripts (they run ./mvnw). Works on Linux, macOS and Git Bash.
#
# File permissions: the files are created owner-only (600). The containers run as other users (Spring services
# uid 10001, Redis and RabbitMQ uid 999) and bind-mount them read-only:
#   - Linux, run as root (the deployment host): each file is chowned to the uid that reads it.
#   - Linux, not root: if setfacl exists, that uid gets a read ACL; otherwise the script prints the chown commands.
#   - Docker Desktop (Windows, macOS) shares files without enforcing these modes; nothing to do.
set -eu

usage() {
    echo "usage: $0 [--force]" >&2
    exit 2
}

force=0
case "${1:-}" in
    --force) force=1 ;;
    "") ;;
    *) usage ;;
esac
[ $# -le 1 ] || usage

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
env_file="$root/.env"
secrets="$root/docker/secrets"

command -v openssl > /dev/null 2>&1 || { echo "openssl is required" >&2; exit 1; }

if [ -e "$env_file" ] && [ "$force" -ne 1 ]; then
    echo "$env_file already exists; refusing to replace it (use --force, and read its notes first)." >&2
    exit 1
fi

umask 077
mkdir -p -- "$secrets"
chmod 700 "$secrets" || true

secret() {
    openssl rand -hex "${1:-24}"
}

# RabbitMQ's rabbit_password_hashing_sha256: base64(salt + sha256(salt + password)), with a 4-byte random salt.
rabbit_hash() {
    tmp=$(mktemp -d)
    openssl rand 4 > "$tmp/salt"
    printf '%s' "$1" > "$tmp/password"
    cat "$tmp/salt" "$tmp/password" | openssl dgst -sha256 -binary > "$tmp/digest"
    cat "$tmp/salt" "$tmp/digest" | openssl base64 -A
    rm -rf -- "$tmp"
}

sha256_hex() {
    printf '%s' "$1" | openssl dgst -sha256 | sed 's/^.*= *//'
}

mysql_root=$(secret); mysql_auth=$(secret); mysql_booking=$(secret); mysql_catalog=$(secret)
mysql_notification=$(secret)
redis_booking=$(secret); redis_gateway=$(secret)
rabbit_admin=$(secret); rabbit_booking=$(secret); rabbit_notification=$(secret)
kafka_admin=$(secret); kafka_booking=$(secret); kafka_catalog=$(secret); kafka_notification=$(secret)
elastic=$(secret); elastic_catalog=$(secret)
eureka=$(secret); config=$(secret)
admin=$(secret)
qr_key=$(secret 32)
s3_access=$(secret 10); s3_secret=$(secret)

tmp_env="$env_file.tmp.$$"
cat > "$tmp_env" <<EOF
# Generated by docker/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Mode 600. NEVER commit this file.
# Rerun with --force to replace every value (read the script's notes on what changes for a running stack).

# MySQL: root (from inside the mysql container only) and one user per service database.
MYSQL_ROOT_PASSWORD=$mysql_root
MYSQL_AUTH_PASSWORD=$mysql_auth
MYSQL_BOOKING_PASSWORD=$mysql_booking
MYSQL_CATALOG_PASSWORD=$mysql_catalog
MYSQL_NOTIFICATION_PASSWORD=$mysql_notification

# Redis: booking's Redis (user "booking": holds, seat streams) and the gateway's own Redis (user "gateway": rate
# limits, token denylist).
REDIS_BOOKING_PASSWORD=$redis_booking
REDIS_GATEWAY_PASSWORD=$redis_gateway

# RabbitMQ: surge-admin (management UI), booking (publishes tickets), notification (consumes them).
RABBIT_ADMIN_PASSWORD=$rabbit_admin
RABBIT_BOOKING_PASSWORD=$rabbit_booking
RABBIT_NOTIFICATION_PASSWORD=$rabbit_notification

# Kafka: admin (PLAIN, broker and kafka-init only) and one SCRAM-SHA-512 user per service.
KAFKA_ADMIN_PASSWORD=$kafka_admin
KAFKA_BOOKING_PASSWORD=$kafka_booking
KAFKA_CATALOG_PASSWORD=$kafka_catalog
KAFKA_NOTIFICATION_PASSWORD=$kafka_notification

# Elasticsearch: the "elastic" superuser (es-init only) and catalog-service's "catalog" user.
ELASTIC_PASSWORD=$elastic
ELASTICSEARCH_CATALOG_PASSWORD=$elastic_catalog

# HTTP Basic for Eureka (discovery) and the config server.
EUREKA_USER=surge
EUREKA_PASSWORD=$eureka
CONFIG_USER=surge
CONFIG_PASSWORD=$config

# The seeded admin account (log in at /login), the ticket QR HMAC key and the S3 keys (S3Mock in compose.dev.yaml
# accepts any; real S3 needs real ones).
SURGE_ADMIN_EMAIL=admin@surge.local
SURGE_ADMIN_PASSWORD=$admin
SURGE_TICKET_QR_KEY=$qr_key
S3_ACCESS_KEY=$s3_access
S3_SECRET_KEY=$s3_secret
EOF
chmod 600 "$tmp_env" || true
mv -f -- "$tmp_env" "$env_file"

# Templates are committed with LF endings; strip any CR a Windows checkout may have added anyway.
redis_acl() { # <user> <password> <output file>
    grep -v '^#' "$root/docker/redis/users.acl.template" | tr -d '\r' \
        | sed -e "s|@@REDIS_USER@@|$1|" -e "s|@@REDIS_PASSWORD_SHA256@@|$(sha256_hex "$2")|" > "$3"
}
redis_acl booking "$redis_booking" "$secrets/redis-users.acl"
redis_acl gateway "$redis_gateway" "$secrets/redis-edge-users.acl"
tr -d '\r' < "$root/docker/rabbitmq/definitions.json.template" \
    | sed -e "s|@@ADMIN_HASH@@|$(rabbit_hash "$rabbit_admin")|" \
          -e "s|@@BOOKING_HASH@@|$(rabbit_hash "$rabbit_booking")|" \
          -e "s|@@NOTIFICATION_HASH@@|$(rabbit_hash "$rabbit_notification")|" > "$secrets/rabbitmq-definitions.json"
chmod 600 "$secrets/redis-users.acl" "$secrets/redis-edge-users.acl" "$secrets/rabbitmq-definitions.json" || true

key_flags=""
[ "$force" -eq 1 ] && key_flags="--force"
if [ -f "$secrets/internal-jwks.json" ] && [ "$force" -ne 1 ]; then
    echo "Keeping the existing internal identity keys in $secrets (use --force to replace them)."
else
    # shellcheck disable=SC2086 # $key_flags is empty or one fixed word
    sh "$root/docker/gen-internal-keys.sh" $key_flags "$secrets"
fi
if [ -f "$secrets/jwt.jwk" ] && [ "$force" -ne 1 ]; then
    echo "Keeping the existing JWT signing key $secrets/jwt.jwk (use --force to replace it)."
else
    # shellcheck disable=SC2086
    sh "$root/docker/gen-jwt-key.sh" $key_flags "$secrets/jwt.jwk"
fi

# Let the container user read its own files (see "File permissions" above).
grant_read() {
    file=$1
    uid=$2
    case "$(uname -s 2> /dev/null || echo unknown)" in
        Linux) ;;
        *) return 0 ;;
    esac
    if [ "$(id -u)" -eq 0 ]; then
        chown "$uid" "$file"
    elif command -v setfacl > /dev/null 2>&1; then
        setfacl -m "u:$uid:r" "$file"
    else
        echo "WARNING: uid $uid cannot read $file (mode 600). Run: sudo chown $uid '$file'" >&2
    fi
}
for key in jwt gateway booking notification; do
    grant_read "$secrets/$key.jwk" 10001
done
grant_read "$secrets/redis-users.acl" 999
grant_read "$secrets/redis-edge-users.acl" 999
grant_read "$secrets/rabbitmq-definitions.json" 999

echo "Wrote $env_file (mode 600) and the files in $secrets. No value was printed."
echo "Admin sign-in: admin@surge.local with SURGE_ADMIN_PASSWORD from .env."
